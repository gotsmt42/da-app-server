const mongoose = require("../db");

/**
 * Signature — "ลายเซ็นอิเล็กทรอนิกส์ปัจจุบัน" ของพนักงานแต่ละคน (1 คน 1 แถว)
 *
 * ✅ ผู้ใช้ขอ: ตั้งค่าลายเซ็นไว้ที่ user แล้วนำไปใช้กับเอกสาร PDF ที่ออกจากระบบทั้งหมด
 * พนักงานเซ็นครั้งเดียวในหน้าตั้งค่า แล้วทุกใบที่ตัวเองเป็นคนออก/อนุมัติจะมีลายเซ็นขึ้นให้เอง
 * ไม่ต้องพรินต์ออกมาเซ็นมือแล้วสแกนกลับเข้าระบบทุกใบ
 *
 * 🔒 ทำไมแยกคอลเลกชัน ไม่เก็บใน User: GET /api/auth/alluser คืนเอกสาร User ทั้งก้อนให้ทุกคนที่
 * ล็อกอิน ถ้าเก็บรูปลายเซ็นไว้ใน User ลายเซ็นของทุกคน (รวมผู้บริหาร) จะหลุดถึงพนักงานทุกคนทันที
 * และเอาไปแปะเอกสารปลอมได้ — ที่นี่เจ้าของเท่านั้นที่ดึงรูปของตัวเองได้ (routes/signatures.js)
 * ส่วนคนอื่นเห็นลายเซ็นได้เฉพาะ "ที่ถูกผนึกไว้ในเอกสารที่คนนั้นเซ็นจริงแล้ว" เท่านั้น
 *
 * ⚠️ ตัวรูปไม่ได้อยู่ในแถวนี้ — เก็บแยกที่ SignatureImage (อ้างด้วย hash) เพราะ:
 *   • เอกสารเก่าต้องพิมพ์ซ้ำได้เหมือนเดิมเป๊ะ แม้เจ้าตัวจะเปลี่ยนลายเซ็นใหม่ไปแล้ว (อ้าง hash เดิม)
 *   • รูปเดียวกันถูกใช้ในเอกสารหลายพันใบ — เก็บครั้งเดียวต่อหนึ่งลายเซ็น ไม่ใช่ทำสำเนาลงทุกใบ
 *     (ถ้าฝังรูปลงทุกเอกสาร ฐานข้อมูลจะบวมเร็วมากและพัง quota ของแผนที่ใช้อยู่)
 */
const signatureSchema = new mongoose.Schema(
  {
    userId: { type: String, required: true, unique: true, index: true },
    /** sha256 ของ dataURL รูปลายเซ็น — ชี้ไปที่ SignatureImage.hash */
    hash: { type: String, required: true },
    /** ผู้ใช้กดยอมรับว่าจะใช้ลายเซ็นนี้แทนการเซ็นด้วยมือเมื่อใด (หลักฐานความยินยอม) */
    consentAt: { type: Date, default: Date.now },
    /** "draw" = วาดเอง · "upload" = อัปโหลดรูปลายเซ็น — เก็บไว้เพื่อตรวจย้อนหลัง */
    method: { type: String, enum: ["draw", "upload"], default: "draw" },
    /** ⚠️ คนตั้งค่า = เจ้าของบัญชีเสมอ (server ไม่ยอมให้ใครตั้งลายเซ็นแทนคนอื่น) เก็บไว้กันเข้าใจผิด */
    setBy: {
      userId: { type: String, default: "" },
      name: { type: String, default: "" },
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model("Signature", signatureSchema);
